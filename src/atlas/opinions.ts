const agents = generateAgents(42);
const districtNames = new Map(DISTRICTS_DATA.map(district => [district.id, district.name]));

function hash(value: string): number {
  let result = 2166136261;
  for (const character of value) result = Math.imul(result ^ character.charCodeAt(0), 16777619);
  return result >>> 0;
}

function commentsFor(place: PlaceSeed): AtlasAgentComment[] {
  const used = new Set<string>();
  return place.comments.map(([role, topic, sentiment, text], index) => {
    const candidates = agents.filter(agent => agent.profession === PROFESSIONS[role] && !used.has(agent.id));
    const agent = candidates[hash(`${place.id}:${index}`) % candidates.length];
    used.add(agent.id);
    return {
      id: `${place.id}:comment:${index}`, agentId: agent.id, agentName: agent.name,
      profession: agent.profession, districtName: districtNames.get(agent.homeDistrict)!,
      stress: agent.stress, topic, text, sentiment,
    };
  });
}

/** Static fictional voices attached to real map anchors. Deliberately neither
 * ratings nor live LLM output. Missing OSM features are omitted, never replaced
 * with guessed coordinates. Ordering does not depend on input feature order. */
export function createAtlasOpinionPlaces(features: readonly AtlasFeature[]): AtlasOpinionPlace[] {
  const byId = new Map(features.map(feature => [String(feature.id), feature]));
  const infrastructure = INFRASTRUCTURE.flatMap((seed): AtlasOpinionPlace[] => {
    const feature = byId.get(seed.id);
    if (!feature || feature.geometry.type !== 'Point') return [];
    const [longitude, latitude] = feature.geometry.coordinates;
    const category = feature.properties?.category;
    if (!Number.isFinite(longitude) || !Number.isFinite(latitude)
      || longitude < 71.38 || longitude > 71.49 || latitude < 51.08 || latitude > 51.17
      || (category !== 'education' && category !== 'health')) return [];
    return [{ id: seed.id, name: featureName(feature), position: [longitude, latitude], category, comments: commentsFor(seed) }];
  });
  return [...infrastructure, ...PUBLIC_PLACES.map((place): AtlasOpinionPlace => ({
    id: place.id, name: place.name, position: [...place.position], category: 'public', comments: commentsFor(place),
  }))];
}
